// Heads-up push/fold at 1–25 bb, no antes: the small blind shoves or folds, the big blind calls or folds. Computed with
// this site's engine: the all-in equity of every pair of starting hands (Monte Carlo, card removal counted exactly),
// then the equilibrium by fictitious play. Writes src/engine/pushfold.ts.
//
//   node scripts/pushfold.ts        (about two minutes the first time, for the equity table; seeded, so the output is reproducible)
import { writeFileSync } from 'node:fs';
import { equityTable, HANDS } from './equity.ts';

const STACKS = 25;
const ROUNDS = 4000; // fictitious-play iterations per stack

{
  const started = performance.now();
  const { EQ, W } = await equityTable();

  const PUSH: number[][] = [], CALL: number[][] = [];
  for (let S = 1; S <= STACKS; S++) {
    // Payoffs in bb from the start of the hand. Small blind: fold -0.5; shove and get folded to +1; called: equity × 2S − S.
    // Big blind facing a shove: fold −1; call (1 − equity) × 2S − S.
    const push = new Float64Array(169).fill(1), call = new Float64Array(169).fill(0.5);
    const callEv = (j: number) => {
      let num = 0, den = 0;
      for (let i = 0; i < 169; i++) {
        const w = W[i][j] * push[i];
        num += w * ((1 - EQ[i][j]) * 2 * S - S);
        den += w;
      }
      return den ? num / den : -1;
    };
    const pushEv = (i: number) => {
      let num = 0, den = 0;
      for (let j = 0; j < 169; j++) {
        num += W[i][j] * ((1 - call[j]) * 1 + call[j] * (EQ[i][j] * 2 * S - S));
        den += W[i][j];
      }
      return num / den;
    };
    for (let t = 1; t <= ROUNDS; t++) {
      for (let j = 0; j < 169; j++) call[j] += ((callEv(j) > -1 ? 1 : 0) - call[j]) / (t + 1);
      for (let i = 0; i < 169; i++) push[i] += ((pushEv(i) > -0.5 ? 1 : 0) - push[i]) / (t + 1);
    }
    PUSH.push(HANDS.map((_, i) => Math.round((pushEv(i) + 0.5) * 100) / 100));
    CALL.push(HANDS.map((_, j) => Math.round((callEv(j) + 1) * 100) / 100));
  }

  const rows = (table: number[][]) => table.map((r) => `  [${r.join(',')}],`).join('\n');
  writeFileSync(
    new URL('../src/engine/pushfold.ts', import.meta.url),
    `// Generated by scripts/pushfold.ts (heads-up push/fold equilibrium, no antes); don't edit by hand.
// PUSH[s - 1][i]: bb the small blind gains by shoving HANDS[i] instead of folding, s bb deep, against the big blind's
// equilibrium calls. CALL[s - 1][i]: bb the big blind gains by calling a shove with HANDS[i] instead of folding.
// Positive = do it. Hands near 0 are close to indifferent.
export const HANDS = ${JSON.stringify(HANDS)};
export const MAX_STACK = ${STACKS};
export const PUSH: number[][] = [
${rows(PUSH)}
];
export const CALL: number[][] = [
${rows(CALL)}
];
`,
  );
  console.log(`done in ${((performance.now() - started) / 1000).toFixed(0)} s`);
}
