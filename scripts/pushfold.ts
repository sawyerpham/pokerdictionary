// Heads-up push/fold at 1–25 bb, no antes: the small blind shoves or folds, the big blind calls or folds. Computed with
// this site's engine: the all-in equity of every pair of starting hands (Monte Carlo, card removal counted exactly),
// then the equilibrium by fictitious play. Writes src/engine/pushfold.ts.
//
//   node scripts/pushfold.ts        (about a minute on a multi-core machine; seeded, so the output is reproducible)
import { writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { isMainThread, parentPort, Worker, workerData } from 'node:worker_threads';
import { evaluate, handName, type Card } from '../src/engine/cards.ts';

const RANKS = 'AKQJT98765432';
// The 13×13 grid order: pairs on the diagonal, suited above, offsuit below.
const HANDS = [...RANKS].flatMap((a, i) => [...RANKS].map((b, j) => (i === j ? a + b : i < j ? a + b + 's' : b + a + 'o')));
const at = new Map(HANDS.map((h, i) => [h, i]));
const COMBOS: Card[][][] = HANDS.map(() => []);
for (let a = 0; a < 52; a++) for (let b = a + 1; b < 52; b++) COMBOS[at.get(handName([a, b]))!].push([a, b]);
const DEALS = 6000; // per pair of hands: about ±0.6% equity
const STACKS = 25;
const ROUNDS = 4000; // fictitious-play iterations per stack

/** Seeded random numbers (mulberry32), so every run writes the same file. */
function rng(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Hand i's all-in equity against hand j (ties split), and how many card-disjoint combo pairs they have. */
function pair(i: number, j: number): [number, number] {
  const pairs: Card[][] = [];
  for (const x of COMBOS[i]) for (const y of COMBOS[j]) if (!x.includes(y[0]) && !x.includes(y[1])) pairs.push([...x, ...y]);
  const random = rng(i * 169 + j + 1);
  let won = 0;
  for (let k = 0; k < DEALS; k++) {
    const used = pairs[Math.floor(random() * pairs.length)].slice();
    while (used.length < 9) {
      const c = Math.floor(random() * 52);
      if (!used.includes(c)) used.push(c);
    }
    const board = used.slice(4);
    const a = evaluate([used[0], used[1], ...board]), b = evaluate([used[2], used[3], ...board]);
    won += a > b ? 1 : a === b ? 0.5 : 0;
  }
  return [won / DEALS, pairs.length];
}

if (!isMainThread) {
  // A worker: whole rows of the table, against every hand from the row's own onward.
  parentPort!.postMessage((workerData as number[]).map((i) => ({ i, row: HANDS.slice(i).map((_, k) => pair(i, i + k)) })));
} else {
  const started = performance.now();
  const threads = Math.max(1, availableParallelism() - 1);
  const jobs: number[][] = Array.from({ length: threads }, () => []);
  HANDS.forEach((_, i) => jobs[i % threads].push(i));
  const results = await Promise.all(
    jobs.map((rows) => new Promise<{ i: number; row: [number, number][] }[]>((ok, fail) => new Worker(new URL(import.meta.url), { workerData: rows }).on('message', ok).on('error', fail))),
  );
  const EQ = HANDS.map(() => new Float64Array(169)), W = HANDS.map(() => new Float64Array(169));
  for (const { i, row } of results.flat()) {
    row.forEach(([eq, n], k) => {
      const j = i + k;
      EQ[i][j] = eq;
      EQ[j][i] = i === j ? eq : 1 - eq;
      W[i][j] = W[j][i] = n;
    });
  }
  console.log(`equity table: ${((performance.now() - started) / 1000).toFixed(0)} s on ${threads} threads`);

  const PUSH: number[][] = [], CALL: number[][] = [];
  for (let S = 1; S <= STACKS; S++) {
    // Payoffs in bb from the start of the hand. Small blind: fold -0.5; shove and get folded to +1; called: equity × 2S − S.
    // Big blind facing a shove: fold −1; call (1 − equity) × 2S − S.
    const push = new Float64Array(169).fill(1), call = new Float64Array(169).fill(0.5);
    const callEv = (j: number) => {
      let num = 0, den = 0;
      for (let i = 0; i < 169; i++) {
        const w = W[i][j] * push[i];
        num += w * ((1 - EQ[i][j]) * 2 * S - S);
        den += w;
      }
      return den ? num / den : -1;
    };
    const pushEv = (i: number) => {
      let num = 0, den = 0;
      for (let j = 0; j < 169; j++) {
        num += W[i][j] * ((1 - call[j]) * 1 + call[j] * (EQ[i][j] * 2 * S - S));
        den += W[i][j];
      }
      return num / den;
    };
    for (let t = 1; t <= ROUNDS; t++) {
      for (let j = 0; j < 169; j++) call[j] += ((callEv(j) > -1 ? 1 : 0) - call[j]) / (t + 1);
      for (let i = 0; i < 169; i++) push[i] += ((pushEv(i) > -0.5 ? 1 : 0) - push[i]) / (t + 1);
    }
    PUSH.push(HANDS.map((_, i) => Math.round((pushEv(i) + 0.5) * 100) / 100));
    CALL.push(HANDS.map((_, j) => Math.round((callEv(j) + 1) * 100) / 100));
  }

  const rows = (table: number[][]) => table.map((r) => `  [${r.join(',')}],`).join('\n');
  writeFileSync(
    new URL('../src/engine/pushfold.ts', import.meta.url),
    `// Generated by scripts/pushfold.ts (heads-up push/fold equilibrium, no antes); don't edit by hand.
// PUSH[s - 1][i]: bb the small blind gains by shoving HANDS[i] instead of folding, s bb deep, against the big blind's
// equilibrium calls. CALL[s - 1][i]: bb the big blind gains by calling a shove with HANDS[i] instead of folding.
// Positive = do it. Hands near 0 are close to indifferent.
export const HANDS = ${JSON.stringify(HANDS)};
export const MAX_STACK = ${STACKS};
export const PUSH: number[][] = [
${rows(PUSH)}
];
export const CALL: number[][] = [
${rows(CALL)}
];
`,
  );
  console.log(`done in ${((performance.now() - started) / 1000).toFixed(0)} s`);
}
